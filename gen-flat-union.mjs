// Generate a flat literal-union .ts file from fixture.json — same set of dot-paths
// MessageKeys<Messages, NestedKeyOf<Messages>> would produce, but pre-computed
// instead of derived from a recursive conditional type.
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync("fixture.json", "utf8"));
const paths = [];
function walk(node, prefix) {
	for (const k of Object.keys(node)) {
		const path = prefix ? `${prefix}.${k}` : k;
		const v = node[k];
		if (v !== null && typeof v === "object" && !Array.isArray(v)) {
			walk(v, path);
		} else if (typeof v === "string") {
			paths.push(path);
		}
	}
}
walk(data, "");
const lines = [
	"// Generated by gen-flat-union.mjs — do not edit by hand.",
	"// Flat literal-union mirror of MessageKeys<Messages, NestedKeyOf<Messages>>.",
	"export type FlatKeys =",
	...paths.map((p, i) => `\t| "${p}"${i === paths.length - 1 ? ";" : ""}`),
	"",
];
writeFileSync("keys-flat.gen.ts", lines.join("\n"));
console.log(`wrote keys-flat.gen.ts with ${paths.length} keys`);
